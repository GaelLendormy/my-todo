test('ordre : GET différé, refus et double activation sans déplacement local', async ({ page, request }) => {
  const task = await fixture(request, 'Ordre différé')
  await page.goto('/')
  await page.getByRole('button', { name: task.title, exact: true }).click()
  let release!: () => void
  const gate = new Promise<void>(resolve => { release = resolve })
  await page.route('**/api/tasks', async route => { const response = await route.fetch(); await gate; await route.fulfill({ response }) })
  let writes = 0
  let releaseWrite!: () => void
  const writeGate = new Promise<void>(resolve => { releaseWrite = resolve })
  await page.route(`**/api/tasks/${task.id}/steps/order`, async route => { writes++; await writeGate; await route.fulfill({ status: 400, json: {} }) })
  const move = page.getByRole('button', { name: 'Monter l’étape : C', exact: true })
  await page.getByRole('button', { name: 'Actualiser', exact: true }).click()
  await expect(move).toBeDisabled()
  expect(writes).toBe(0)
  release()
  await expect(move).toBeEnabled()
  await move.click()
  await expect(move).toBeDisabled()
  await page.keyboard.press('Enter')
  releaseWrite()
  await expect(page.locator('#save-message')).toContainText('Modification d’étape refusée')
  expect(writes).toBe(1)
  await expect(page.locator('.step-content > p')).toHaveText(['A', 'B', 'C'])
})

test('ordre : conflit externe, relecture et nouveau choix sans réappliquer un tableau ancien', async ({ page, request }) => {
  const task = await fixture(request, 'Ordre conflit')
  const url = `/api/tasks/${task.id}/steps/order`
  await page.goto('/')
  await page.getByRole('button', { name: task.title, exact: true }).click()
  let writes = 0
  await page.route(`**${url}`, async route => { writes++; await route.continue() })
  await request.patch(url, { headers, data: { stepId: task.steps[2]!.id, direction: 'up', expectedOrder: task.steps.map(s => s.id) } })
  await page.getByRole('button', { name: 'Monter l’étape : C', exact: true }).click()
  await expect(page.locator('#save-message')).toContainText('Aucun déplacement effectué')
  await expect(page.getByRole('button', { name: 'Monter l’étape : C', exact: true })).toBeDisabled()
  expect(writes).toBe(1)
  await page.getByRole('button', { name: 'Relire la liste avant de réessayer', exact: true }).click()
  await expect(page.locator('.step-content > p')).toHaveText(['A', 'C', 'B'])
  expect(writes).toBe(1)
  await page.getByRole('button', { name: 'Monter l’étape : C', exact: true }).click()
  await expect(page.locator('.step-content > p')).toHaveText(['C', 'A', 'B'])
  expect(writes).toBe(2)
})

test('ordre : réponse perdue après vraie écriture, relecture partielle et aucune répétition', async ({ page, request }) => {
  const task = await fixture(request, 'Ordre perdu')
  await page.goto('/')
  await page.getByRole('button', { name: task.title, exact: true }).click()
  await page.getByLabel('Titre de la tâche').fill('Brouillon parent')
  await page.getByRole('button', { name: 'Renommer l’étape : B', exact: true }).click()
  await page.getByLabel('Nouveau titre de l’étape').fill('Brouillon renommage')
  await page.getByLabel('Nouvelle étape', { exact: true }).fill('Brouillon ajout')
  await page.clock.install()
  let writes = 0
  await page.route(`**/api/tasks/${task.id}/steps/order`, async route => { await route.fetch(); writes++ })
  await page.getByRole('button', { name: 'Monter l’étape : C', exact: true }).click()
  await expect.poll(() => writes).toBe(1)
  await page.clock.runFor(10_001)
  await expect(page.locator('#save-message')).toContainText('Résultat à vérifier')
  await page.clock.runFor(30_000)
  expect(writes).toBe(1)
  await expect(page.locator('.step-content > p')).toHaveText(['A', 'B', 'C'])
  for (const name of ['Ajouter', 'Enregistrer', 'Ajouter une étape', 'Enregistrer le titre de l’étape', 'Supprimer la tâche', 'Monter l’étape : C']) await expect(page.getByRole('button', { name, exact: true })).toBeDisabled()
  await page.route('**/api/categories', route => route.fulfill({ status: 503, json: {} }))
  await page.getByRole('button', { name: 'Relire la liste avant de réessayer', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Impossible de charger')
  await expect(page.locator('.step-content > p')).toHaveText(['A', 'B', 'C'])
  await expect(page.getByRole('button', { name: 'Monter l’étape : C', exact: true })).toBeDisabled()
  await page.unroute('**/api/categories')
  await page.getByRole('button', { name: 'Relire la liste avant de réessayer', exact: true }).click()
  await expect(page.locator('.step-content > p')).toHaveText(['A', 'C', 'B'])
  await expect(page.getByLabel('Titre de la tâche')).toHaveValue('Brouillon parent')
  await expect(page.getByLabel('Nouveau titre de l’étape')).toHaveValue('Brouillon renommage')
  await expect(page.getByLabel('Nouvelle étape', { exact: true })).toHaveValue('Brouillon ajout')
  expect(writes).toBe(1)
})
