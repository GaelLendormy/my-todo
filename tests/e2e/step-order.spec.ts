import { expect, test } from '@playwright/test'
import type { APIRequestContext } from '@playwright/test'
import type { Task } from '../../shared/types/task'
const headers = { Origin: 'http://127.0.0.1:3100' }
async function fixture(request: APIRequestContext, title: string) {
  let task = await request.post('/api/tasks', { headers, data: { title: `${title} ${Date.now()}` } }).then(r => r.json()) as Task
  for (const title of ['A', 'B', 'C']) task = await request.post(`/api/tasks/${task.id}/steps`, { headers, data: { title } }).then(r => r.json()) as Task
  await request.patch(`/api/tasks/${task.id}/steps/${task.steps[1]!.id}`, { headers, data: { completed: true } })
  return task
}
